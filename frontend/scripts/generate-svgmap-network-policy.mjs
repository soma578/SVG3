#!/usr/bin/env node
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const frontendRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const projectRoot = path.resolve(frontendRoot, '..')
const upstreamRoot = path.join(projectRoot, 'svgMapAppLayers')
const outputPath = path.join(frontendRoot, 'lib', 'generatedSvgMapAppLayerTargets.mjs')
const baselinePath = path.join(
  projectRoot,
  'map',
  'layers',
  'external',
  'svgmap-app-layers',
  'upstream-network-baseline.json',
)

const ignoredHosts = new Set([
  'mozilla.org',
  'opengis.org',
  'purl.org',
  'service.svgmap.org', // 外部の汎用中継をさらに中継しない
  'www.w3.org',
])
const runtimeHint = /(?:fetch|XMLHttpRequest|getCORSURL|baseURL|serverURL|proxyPath|proxyUrl|indexUrl|pageBase|tile|wmts|wms|api)/i
const targets = new Map()
const writeBaseline = process.argv.includes('--write-baseline')

const addTarget = (hostname, pathname, allowRoot) => {
  const host = String(hostname || '').toLowerCase()
  if (!/^[a-z0-9.-]+$/.test(host) || !host.includes('.') || ignoredHosts.has(host)) return
  let prefix = String(pathname || '/').replaceAll('&amp;', '&').split(/[?#]/)[0] || '/'
  const placeholder = prefix.search(/(?:\$\{|\[\[|\{[A-Za-z])/)
  if (placeholder >= 0) prefix = prefix.slice(0, placeholder)
  if (!prefix.startsWith('/')) prefix = `/${prefix}`
  if (prefix === '/' && !allowRoot) return
  if (!targets.has(host)) targets.set(host, new Set())
  targets.get(host).add(prefix)
}

const scan = (file) => {
  let source
  try {
    source = fs.readFileSync(file, 'utf8')
  } catch {
    return
  }
  for (const match of source.matchAll(/https?:\/\/([^/"'`\s<>)\\]+)(\/[^"'`\s<>)\\]*)?/g)) {
    const context = source.slice(Math.max(0, match.index - 180), match.index + match[0].length + 180)
    addTarget(match[1], match[2] || '/', runtimeHint.test(context))
  }
}

const walk = (directory) => {
  for (const entry of fs.readdirSync(directory, { withFileTypes: true })) {
    if (entry.name.endsWith(':Zone.Identifier')
      || ['.git', 'node_modules', 'test', 'tests'].includes(entry.name)
      || /\.test\.[cm]?js$/i.test(entry.name)) continue
    const file = path.join(directory, entry.name)
    if (entry.isDirectory()) walk(file)
    else if (entry.isFile()) scan(file)
  }
}

if (!writeBaseline && fs.existsSync(baselinePath)) {
  const baseline = JSON.parse(fs.readFileSync(baselinePath, 'utf8'))
  for (const target of baseline.targets || []) {
    for (const prefix of target.pathnamePrefixes || []) addTarget(target.hostname, prefix, true)
  }
}
walk(upstreamRoot)
const additionalRoot = process.env.SVG3_UPSTREAM_NETWORK_ROOT
if (additionalRoot && fs.existsSync(additionalRoot)) walk(path.resolve(additionalRoot))
const policy = [...targets]
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([hostname, prefixes]) => ({
    hostname,
    pathnamePrefixes: [...prefixes].sort((a, b) => a.length - b.length || a.localeCompare(b)),
  }))

const body = [
  '// Generated by scripts/generate-svgmap-network-policy.mjs. Do not edit by hand.',
  `export const GENERATED_SVGMAP_APP_LAYER_TARGETS = Object.freeze(${JSON.stringify(policy, null, 2)})`,
  '',
].join('\n')
fs.mkdirSync(path.dirname(outputPath), { recursive: true })
fs.writeFileSync(outputPath, body)
if (writeBaseline) {
  fs.mkdirSync(path.dirname(baselinePath), { recursive: true })
  fs.writeFileSync(baselinePath, `${JSON.stringify({
    schemaVersion: 1,
    source: 'SVGMap App Layers upstream snapshot',
    targets: policy,
  }, null, 2)}\n`)
}
console.log(`[svgmap-network-policy] ${policy.length} host(s), ${policy.reduce((n, entry) => n + entry.pathnamePrefixes.length, 0)} path prefix(es)`)
