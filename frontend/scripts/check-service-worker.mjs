#!/usr/bin/env node
/**
 * Service Worker の契約検査
 * =========================
 * 最も守りたいのは「SW が動的防災データを肩代わりしない」こと。
 * そこが崩れると鮮度バナーが黙って死に、古い避難所情報が最新に見える。
 */
import assert from 'node:assert/strict'
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const scriptDir = path.dirname(fileURLToPath(import.meta.url))
const projectRoot = path.resolve(scriptDir, '..', '..')
const mapRoot = path.join(projectRoot, 'map')

const read = (relative) => fs.readFileSync(path.join(mapRoot, relative), 'utf8')

const swPath = path.join(mapRoot, 'sw.js')
assert.ok(fs.existsSync(swPath), 'map/sw.js is missing — run npm run sw:generate')
const sw = fs.readFileSync(swPath, 'utf8')
const swBody = read('webapp/sw.body.js')
const policy = read('webapp/shared/swCachePolicy.js')
const nativeShell = read('webapp/native-map.js')
const nativeHtml = read('webapp/native-map.html')

// --- 生成物が最新であること -------------------------------------------------
assert.ok(sw.includes('GENERATED by frontend/scripts/generate-service-worker.mjs'), 'map/sw.js must be generated')
const shellVersion = sw.match(/^\/\/ shell version: ([0-9a-f]{12})/m)?.[1]
const regionVersion = sw.match(/^\/\/ region version: ([0-9a-f]{12})/m)?.[1]
assert.ok(shellVersion, 'generated sw.js must record its shell version')
assert.ok(regionVersion, 'generated sw.js must record its region version')
assert.ok(
  sw.includes(`const SHELL_VERSION = "${shellVersion}"`),
  'shell version placeholder was not substituted',
)
assert.ok(!sw.includes('__SHELL_ASSETS__'), 'shell asset list placeholder was not substituted')
assert.ok(!/^\s*(import|export)\s/m.test(sw), 'generated sw.js must be a classic script (iOS Safari has no module SW)')

// --- 動的データを肩代わりしないこと -----------------------------------------
assert.ok(
  policy.includes("'/map/data/'"),
  'cache policy must treat /map/data/ as dynamic',
)
for (const dynamicPath of ['/map/data/', '/map/distribution/']) {
  assert.ok(sw.includes(dynamicPath), `generated sw.js lost the dynamic prefix ${dynamicPath}`)
}
// respondWith は shell と region の分岐でのみ呼ぶ。
const respondWithCount = (swBody.match(/event\.respondWith\(/g) || []).length
assert.equal(respondWithCount, 2, 'sw.body.js must call respondWith only for shell and region')
assert.ok(
  /if \(kind === 'shell'\)[\s\S]{0,200}event\.respondWith/.test(swBody),
  'shell requests must be served from the shell cache',
)
assert.ok(
  /if \(kind === 'region'\)[\s\S]{0,200}event\.respondWith/.test(swBody),
  'region requests must be served from a region cache',
)
// 動的データを保存する経路が生えていないこと。
assert.ok(
  !/kind === 'dynamic'[\s\S]{0,200}(cache\.put|respondWith)/.test(swBody),
  'the service worker must never cache or answer dynamic disaster data',
)
// shell 資産一覧に動的データが混ざっていないこと。
const shellAssets = JSON.parse(sw.match(/const SHELL_ASSETS = (\[[\s\S]*?\]);/)?.[1] || '[]')
assert.ok(shellAssets.length > 0, 'shell asset list must not be empty')
for (const asset of shellAssets) {
  assert.ok(
    !asset.startsWith('/map/data/') && !asset.startsWith('/map/distribution/'),
    `shell asset list must not contain dynamic data: ${asset}`,
  )
}
// 生成物が古いままだと、新しく足したモジュールが shell 一覧に無く、
// オフラインで import が失敗してレイヤーが初期化できない（実際に踏んだ）。
// ディスク上の実ファイルと突き合わせて、生成が最新かを確かめる。
{
  const shellDirectories = [
    { root: mapRoot, dir: 'webapp', urlBase: '/map/webapp', extensions: ['.html', '.css', '.js'] },
    { root: mapRoot, dir: 'vendor/svgmapjs', urlBase: '/map/vendor/svgmapjs', extensions: ['.js', '.html'] },
    { root: mapRoot, dir: 'layers/portable', urlBase: '/map/layers/portable', extensions: ['.js', '.html', '.svg', '.json'] },
    { root: mapRoot, dir: 'icons', urlBase: '/map/icons', extensions: ['.svg', '.png'] },
    { root: projectRoot, dir: 'svgMapAppLayers/basemaps', urlBase: '/map/svgMapAppLayers/basemaps', extensions: ['.svg'] },
  ]
  const excluded = new Set(['/map/webapp/sw.body.js'])
  const onDisk = new Set()
  const walk = (root, urlBase, extensions) => {
    if (!fs.existsSync(root)) return
    for (const entry of fs.readdirSync(root, { withFileTypes: true })) {
      const full = path.join(root, entry.name)
      if (entry.isDirectory()) {
        walk(full, `${urlBase}/${entry.name}`, extensions)
        continue
      }
      if (entry.name.includes(':Zone.Identifier')) continue
      if (!extensions.includes(path.extname(entry.name))) continue
      const url = `${urlBase}/${entry.name}`
      if (!excluded.has(url)) onDisk.add(url)
    }
  }
  for (const spec of shellDirectories) walk(path.join(spec.root, spec.dir), spec.urlBase, spec.extensions)

  const listed = new Set(shellAssets)
  const missing = [...onDisk].filter((url) => !listed.has(url)).sort()
  assert.deepEqual(
    missing,
    [],
    `map/sw.js is stale — run npm run sw:generate (missing: ${missing.slice(0, 5).join(', ')})`,
  )
}

// 起動に要るものが実際に入っていること。
for (const required of [
  '/map/webapp/native-map.html',
  '/map/webapp/current-map.html',
  '/map/webapp/native-map.js',
  '/map/webapp/native-map.css',
  '/map/layers/catalog.json',
  '/map/regions/index.json',
  '/manifest.webmanifest',
]) {
  assert.ok(shellAssets.includes(required), `shell asset list is missing ${required}`)
}
assert.ok(
  shellAssets.some((asset) => asset.startsWith('/map/vendor/svgmapjs/')),
  'shell asset list must include the SVGMap runtime',
)
// 一度、生成器が存在しないディレクトリを見ていて基図レイヤー定義が黙って
// 抜けていた。Container が参照する外部レイヤー定義は shell に無ければならない。
assert.ok(
  shellAssets.includes('/map/svgMapAppLayers/basemaps/dynamicDenshiKokudo2016.svg'),
  'shell asset list must include the basemap layer definition referenced by every container',
)
assert.ok(
  !shellAssets.includes('/map/webapp/sw.body.js'),
  'the service worker template is a build input, not a shipped asset',
)

// --- キャッシュの版管理 -----------------------------------------------------
assert.ok(
  /svg3-shell-/.test(sw) && /svg3-region-/.test(sw),
  'cache names must be explicitly namespaced and versioned',
)
assert.ok(
  policy.includes('parsed.kind === \'region\' && regionVersion'),
  'region caches must only be dropped when their own version changes',
)

// 動的シャードは SW キャッシュではなく runtimeCache の保管庫へ入れること。
// SW 側で respondWith しない以上、保存先を間違えると保存したのに使われない。
assert.ok(
  swBody.includes('RUNTIME_DATA_CACHE_NAME'),
  'sw.body.js must seed region data shards into the runtime data cache',
)
assert.ok(
  swBody.includes('RUNTIME_STORED_AT_HEADER'),
  'sw.body.js must stamp the stored-at header so freshness stays reportable',
)
assert.ok(
  !/cache\.put\(\s*url/.test(swBody),
  'sw.body.js must not put data shards into the region cache',
)

// --- 地域資産マニフェスト ---------------------------------------------------
const regionsRoot = path.join(mapRoot, 'regions')
const regionIds = fs.readdirSync(regionsRoot, { withFileTypes: true })
  .filter((entry) => entry.isDirectory())
  .map((entry) => entry.name)
assert.ok(regionIds.length >= 47, `expected at least 47 regions, found ${regionIds.length}`)
// 全国 detail の総数。地域マニフェストが全国分を抱えていないかの基準にする。
const nationalDetailShardCount = (() => {
  const indexPath = path.join(mapRoot, 'data/qtct/evacuation/detail-index.json')
  if (!fs.existsSync(indexPath)) return 0
  const index = JSON.parse(fs.readFileSync(indexPath, 'utf8'))
  return Array.isArray(index.shards) ? index.shards.length : 0
})()
assert.ok(nationalDetailShardCount > 0, 'national detail shard index is missing — run npm run generate:representative-qtct')

let manifestCount = 0
for (const regionId of regionIds) {
  const manifestPath = path.join(regionsRoot, regionId, 'asset-manifest.json')
  if (!fs.existsSync(path.join(regionsRoot, regionId, 'runtime-config.json'))) continue
  assert.ok(fs.existsSync(manifestPath), `${regionId} is missing asset-manifest.json`)
  const manifest = JSON.parse(fs.readFileSync(manifestPath, 'utf8'))
  assert.equal(manifest.kind, 'svg3-region-assets', `${regionId} manifest kind`)
  assert.equal(manifest.regionId, regionId, `${regionId} manifest regionId`)
  assert.ok(Array.isArray(manifest.assets) && manifest.assets.length > 0, `${regionId} manifest assets`)
  for (const asset of manifest.assets) {
    assert.ok(asset.startsWith('/'), `${regionId}: asset must be an absolute path: ${asset}`)
    assert.ok(
      !asset.startsWith('/map/data/') && !asset.startsWith('/map/distribution/'),
      `${regionId}: region manifest must not contain dynamic data: ${asset}`,
    )
    const file = path.join(projectRoot, asset.replace(/^\//, ''))
    assert.ok(fs.existsSync(file), `${regionId}: manifest references a missing file: ${asset}`)
  }
  // dataShards: 県の範囲に交差する分だけ。全国 detail 全体を含めてはいけない。
  assert.ok(Array.isArray(manifest.dataShards), `${regionId} manifest dataShards must be an array`)
  for (const shard of manifest.dataShards) {
    assert.ok(
      shard.startsWith('/map/data/qtct/') && !shard.includes('..'),
      `${regionId}: dataShards must stay under /map/data/qtct/: ${shard}`,
    )
    assert.ok(
      fs.existsSync(path.join(projectRoot, shard.replace(/^\//, ''))),
      `${regionId}: dataShards references a missing file: ${shard}`,
    )
  }
  const detailShards = manifest.dataShards.filter((shard) => shard.includes('/detail/'))
  assert.ok(
    detailShards.length <= nationalDetailShardCount * 0.25,
    `${regionId}: region manifest carries ${detailShards.length} of ${nationalDetailShardCount} `
    + 'national detail shards — region save must not pull the whole country',
  )
  manifestCount += 1
}

// --- ページ側の配線 ---------------------------------------------------------
assert.ok(
  nativeShell.includes("from './shared/swClient.js'"),
  'native host must use the shared service worker client',
)
assert.ok(nativeShell.includes('registerServiceWorker()'), 'native host must register the service worker')
assert.ok(nativeShell.includes('cacheRegion('), 'native host must cache the region it displays')
assert.ok(
  nativeHtml.includes('rel="manifest"'),
  'native host must link the PWA manifest',
)
// SW が使えない環境でオンライン利用が壊れないこと。
const swClient = read('webapp/shared/swClient.js')
assert.ok(
  swClient.includes('serviceWorkerSupported'),
  'the client must degrade when service workers are unavailable',
)
assert.ok(
  /registerServiceWorker[\s\S]{0,400}catch/.test(swClient),
  'registration failure must not break online use',
)

// --- PWA manifest -----------------------------------------------------------
const manifest = JSON.parse(read('webapp/manifest.webmanifest'))
for (const field of ['name', 'short_name', 'start_url', 'scope', 'display', 'theme_color', 'background_color']) {
  assert.ok(manifest[field], `manifest is missing ${field}`)
}
assert.ok(Array.isArray(manifest.icons) && manifest.icons.length >= 2, 'manifest needs icons')
for (const icon of manifest.icons) {
  const file = path.join(projectRoot, icon.src.replace(/^\//, ''))
  assert.ok(fs.existsSync(file), `manifest icon is missing: ${icon.src}`)
}
assert.ok(
  manifest.start_url.startsWith(manifest.scope),
  'start_url must be inside scope or offline start will fail',
)

// --- pin / 実在確認 / 縮退 ---------------------------------------------------
const policySource = read('webapp/shared/swCachePolicy.js')
assert.ok(
  /regionsToEvict\s*=\s*\([^)]*pinned/.test(policySource),
  'LRU eviction must take pinned regions into account',
)
assert.ok(
  policySource.includes('export') && policySource.includes('planRegionCache'),
  'capacity planning must be a testable pure function',
)
assert.ok(
  /needsChoice:\s*true/.test(policySource),
  'a full cache of pinned regions must ask the user instead of deleting silently',
)
assert.ok(
  /if \(!cacheExists \|\| storedCount === 0\) return \{ \.\.\.base, state: 'absent' \}/.test(policySource),
  'a region with metadata but no real cache must not be reported as saved',
)
assert.ok(
  /storedCount < expected/.test(policySource),
  'a partially stored region must not be reported as saved',
)
const swBodySource = read('webapp/sw.body.js')
assert.ok(
  swBodySource.includes('inspectRegionCache'),
  'the service worker must verify real cache contents before reporting saved regions',
)
assert.ok(
  /await caches\.delete\(SHELL_CACHE\);[\s\S]{0,120}throw new Error/.test(swBodySource),
  'an incomplete shell install must fail so the previous service worker keeps serving',
)
// 保存操作は状態の読み書きを伴う。並走すると互いに古い状態を見て上限を超える。
assert.ok(
  swBodySource.includes('serializeMutation'),
  'region cache mutations must be serialized or the cap can be exceeded',
)
for (const call of ['cacheRegion(message.regionId', 'removeRegion(message.regionId', 'listCachedRegions']) {
  assert.ok(
    new RegExp(`serializeMutation\\([\\s\\S]{0,80}${call.replace(/[(.]/g, '\\$&')}`).test(swBodySource),
    `${call} must run inside serializeMutation`,
  )
}

// --- オフライン背景 ---------------------------------------------------------
const basemapDir = path.join(mapRoot, 'layers', 'offline-basemap')
assert.ok(fs.existsSync(basemapDir), 'offline basemaps are missing — run npm run generate:offline-basemap')
const basemaps = fs.readdirSync(basemapDir).filter((name) => name.endsWith('.svg'))
assert.ok(basemaps.length >= 47, `expected 47 offline basemaps, found ${basemaps.length}`)
let basemapBytes = 0
for (const name of basemaps) {
  const bytes = fs.statSync(path.join(basemapDir, name)).size
  basemapBytes += bytes
  // 軽量であることが要件。重い背景は保存できず意味がない。
  assert.ok(bytes < 400_000, `offline basemap ${name} is ${bytes} bytes (budget 400000)`)
}
// 地域マニフェストへ入っていなければオフラインで白地になる。
for (const regionId of regionIds) {
  const manifestPath = path.join(regionsRoot, regionId, 'asset-manifest.json')
  if (!fs.existsSync(manifestPath)) continue
  const regionManifest = JSON.parse(fs.readFileSync(manifestPath, 'utf8'))
  assert.ok(
    regionManifest.assets.some((asset) => asset.startsWith('/map/layers/offline-basemap/')),
    `${regionId}: region manifest must include the offline basemap`,
  )
}

// --- ハザードの縮退 ---------------------------------------------------------
const hazardLayer = read('layers/portable/hazard/hazardLayer.html')
const hazardFallback = read('layers/portable/hazard/hazardFallback.js')
assert.ok(
  hazardFallback.includes('export const hazardDisplayPlan'),
  'hazard degradation must be a testable pure function',
)
assert.ok(
  hazardFallback.includes('市区町村詳細は取得できないため県全体版を表示中'),
  'the degraded hazard notice must state what is being shown',
)
assert.ok(
  hazardLayer.includes('hazardDisplayPlan'),
  'the hazard layer must use the degradation plan',
)
assert.ok(
  hazardLayer.includes('id="hazard-degraded"'),
  'the hazard layer must surface the degraded state to the user',
)

console.log(`[check-service-worker] OK: shell ${shellVersion} (${shellAssets.length} assets), region ${regionVersion} (${manifestCount} manifests), ${basemaps.length} offline basemaps (${(basemapBytes / 1024 / 1024).toFixed(1)} MiB)`)
